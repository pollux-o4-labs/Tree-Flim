export function makeSlots(photos: readonly Photo[], columnCount = 5) {
  const positions = Array.from({ length: 15 }, (_, i) => i);
  const shuffledPhotos = [...photos];
  for (let i = shuffledPhotos.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffledPhotos[i], shuffledPhotos[j]] = [shuffledPhotos[j], shuffledPhotos[i]];
  }
  for (let i = positions.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [positions[i], positions[j]] = [positions[j], positions[i]];
  }
  const rowCount = Math.ceil(positions.length / columnCount);
  const selectedCount = Math.min(3, columnCount, rowCount);
  const selectedRows = positions
    .map((position) => Math.floor(position / columnCount))
    .filter((row, index, rows) => rows.indexOf(row) === index)
    .sort(() => Math.random() - 0.5)
    .slice(0, selectedCount);
  const selectedColumns = Array.from({ length: columnCount }, (_, column) => column)
    .sort(() => Math.random() - 0.5)
    .slice(0, selectedCount);
  const selectedPositions = selectedRows
    .map((row, index) => row * columnCount + selectedColumns[index])
    .sort((a, b) => a - b);
  let background = 3;
  return Array.from({ length: 15 }, (_, i) => ({
    photo: selectedPositions.includes(i)
      ? shuffledPhotos[selectedPositions.indexOf(i)]
      : photos[background++ % photos.length],
    featured: selectedPositions.includes(i),
  }));
}
